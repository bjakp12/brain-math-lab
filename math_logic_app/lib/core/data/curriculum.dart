TopicMeta? topicMeta(String id) {
  for (final t in kTopics()) {
    if (t.id == id) return t;
  }
  return null;
}

List<TopicMeta> topicsOf(String categoryId) =>
    kTopics().where((t) => t.categoryId == categoryId).toList();

List<String> topicIdsOf(String categoryId) =>
    topicsOf(categoryId).map((t) => t.id).toList();
